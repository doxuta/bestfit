// Command gen regenerates a fallback table from the vendor mapping files on
// unicode.org and verifies every row against golang.org/x/text. It is run by
// go generate in the cp932 and cp949 packages.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"golang.org/x/text/encoding"
	"golang.org/x/text/encoding/japanese"
	"golang.org/x/text/encoding/korean"
)

const mappings = "https://www.unicode.org/Public/MAPPINGS/"

func main() {
	cp := flag.String("cp", "", "932 or 949")
	out := flag.String("o", "", "output file")
	flag.Parse()
	var base encoding.Encoding
	switch *cp {
	case "932":
		base = japanese.ShiftJIS
	case "949":
		base = korean.EUCKR
	default:
		log.Fatal("-cp must be 932 or 949")
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run ../internal/gen -cp %s; DO NOT EDIT.\n\npackage cp%s\n\nimport \"github.com/doxuta/bestfit\"\n", *cp, *cp)

	if *cp == "932" {
		sj := parseTwoCol(fetch(mappings + "OBSOLETE/EASTASIA/JIS/SHIFTJIS.TXT"))
		ms := parseTwoCol(fetch(mappings + "VENDORS/MICSFT/WINDOWS/CP932.TXT"))
		jis := map[rune]string{}
		for by, u := range sj {
			mu, ok := ms[by]
			if !ok || mu == u {
				continue
			}
			if _, err := encode(base, rune(u)); err == nil {
				log.Printf("JIS: skip U+%04X, base already writes it", u)
				continue
			}
			got, err := encode(base, rune(mu))
			if err != nil || !bytes.Equal(got, toBytes(by)) {
				log.Fatalf("JIS: U+%04X -> U+%04X does not encode to %X (got %X, %v)", u, mu, by, got, err)
			}
			jis[rune(u)] = string(rune(mu))
		}
		writeTable(&b, "JIS", jis,
			"JIS holds the SHIFTJIS.TXT rows (the JIS X 0208 mapping used by Apple, glibc and iconv)\n"+
				"whose bytes CP932.TXT (Microsoft) assigns to a different code point. The WHATWG\n"+
				"Shift_JIS encoder's three special cases (¥→0x5C, ‾→0x7E, −→－) are among them.")
	}

	mb, wc := parseBestFit(fetch(mappings + "VENDORS/MICSFT/WindowsBestFit/bestfit" + *cp + ".txt"))
	win := map[rune]string{}
	var roundtrip, noMB, encodable, mismatch int
	for _, e := range wc {
		target, ok := mb[e.b]
		switch {
		case ok && target == e.u:
			roundtrip++
			continue
		case !ok:
			noMB++
			continue
		}
		if got, err := encode(base, rune(e.u)); err == nil {
			encodable++
			log.Printf("Windows: skip U+%04X -> %X, base already writes it as %X", e.u, e.b, got)
			continue
		}
		got, err := encode(base, rune(target))
		if err != nil || !bytes.Equal(got, toBytes(e.b)) {
			mismatch++
			log.Printf("Windows: skip U+%04X -> %X (decodes to U+%04X, which base writes as %X, %v)", e.u, e.b, target, got, err)
			continue
		}
		win[rune(e.u)] = string(rune(target))
	}
	log.Printf("bestfit%s: %d WCTABLE rows: %d round-trip, %d no MBTABLE entry, %d base already writes, %d mismatch, %d kept",
		*cp, len(wc), roundtrip, noMB, encodable, mismatch, len(win))
	writeTable(&b, "Windows", win,
		"Windows holds the bestfit"+*cp+".txt WCTABLE rows that do not round-trip: what\n"+
			"WideCharToMultiByte writes when WC_NO_BEST_FIT_CHARS is not set. Only rows the\n"+
			"base encoding refuses are kept.")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func writeTable(b *bytes.Buffer, name string, t map[rune]string, doc string) {
	keys := make([]int, 0, len(t))
	for r := range t {
		keys = append(keys, int(r))
	}
	sort.Ints(keys)
	fmt.Fprintf(b, "\n// %s\n// %d rows.\nvar %s = bestfit.Table{\n", strings.ReplaceAll(doc, "\n", "\n// "), len(t), name)
	for _, k := range keys {
		r := rune(k)
		fmt.Fprintf(b, "\t0x%04X: %q,", r, t[r])
		if unicode.IsPrint(r) && !unicode.IsSpace(r) {
			fmt.Fprintf(b, " // %c", r)
		}
		b.WriteString("\n")
	}
	b.WriteString("}\n")
}

func encode(e encoding.Encoding, r rune) ([]byte, error) {
	return e.NewEncoder().Bytes([]byte(string(r)))
}

func toBytes(b int) []byte {
	if b < 0x100 {
		return []byte{byte(b)}
	}
	return []byte{byte(b >> 8), byte(b)}
}

func fetch(url string) []byte {
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != 200 {
		log.Fatalf("%s: %s", url, resp.Status)
	}
	data, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	return data
}

// parseTwoCol reads "0xBYTES<tab>0xUNICODE" rows; rows without a code point
// (#UNDEFINED) are skipped.
func parseTwoCol(data []byte) map[int]int {
	m := map[int]int{}
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		f := strings.Fields(sc.Text())
		if len(f) < 2 || !strings.HasPrefix(f[0], "0x") || !strings.HasPrefix(f[1], "0x") {
			continue
		}
		m[hex(f[0])] = hex(f[1])
	}
	return m
}

type wcRow struct{ u, b int }

var leadByte = regexp.MustCompile(`LeadByte\s*=\s*0x([0-9a-fA-F]+)`)

// parseBestFit reads a WindowsBestFit file: MBTABLE and DBCSTABLE sections
// give bytes→code point, WCTABLE gives code point→bytes.
func parseBestFit(data []byte) (mb map[int]int, wc []wcRow) {
	mb = map[int]int{}
	section, lead := "", 0
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line, comment, _ := strings.Cut(sc.Text(), ";")
		f := strings.Fields(line)
		if len(f) == 0 {
			continue
		}
		switch f[0] {
		case "CODEPAGE", "CPINFO", "MBTABLE", "WCTABLE", "DBCSRANGE", "DBCSTABLE", "ENDCODEPAGE":
			section = f[0]
			if section == "DBCSTABLE" {
				lead = hex("0x" + leadByte.FindStringSubmatch(comment)[1])
			}
			continue
		}
		switch section {
		case "MBTABLE":
			mb[hex(f[0])] = hex(f[1])
		case "DBCSTABLE":
			mb[lead<<8|hex(f[0])] = hex(f[1])
		case "WCTABLE":
			wc = append(wc, wcRow{u: hex(f[0]), b: hex(f[1])})
		}
	}
	return mb, wc
}

func hex(s string) int {
	n, err := strconv.ParseInt(strings.TrimPrefix(s, "0x"), 16, 32)
	if err != nil {
		log.Fatal(err)
	}
	return int(n)
}
